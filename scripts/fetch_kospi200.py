df = fdr.StockListing('KOSPI')
df['Code'] = df['Code'].astype(str).str.zfill(6)
df200 = df[df['Code'].isin(KOSPI200_CODES)].copy()

stocks_by_sector = {}
for _, row in df200.iterrows():
    code = row['Code']
    name = CODE_NAMES.get(code, str(row['Name']))
    sector = SECTOR_MAP.get(code, '기타')

    close = int(row['Close'])
    change = int(row['Changes'])
    change_rate = float(row['ChagesRatio'])
    volume = int(row['Volume'])
    marcap_billion = int(row['Marcap']) // 100000000

    stock_data = {
        "code": code,
        "name": name,
        "close": f"{close:,}",
        "change": f"{'+' if change >= 0 else ''}{change:,}",
        "changeRate": f"{'+' if change_rate >= 0 else ''}{change_rate:.2f}",
        "volume": f"{volume:,}",
        "marketCap": f"{marcap_billion:,}",
        "sector": sector
    }

    if sector not in stocks_by_sector:
        stocks_by_sector[sector] = []
    stocks_by_sector[sector].append(stock_data)

for sector in stocks_by_sector:
    stocks_by_sector[sector].sort(
        key=lambda x: int(x['marketCap'].replace(',', '')),
        reverse=True
    )

